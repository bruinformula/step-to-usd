// Write CAD pat
void StepUsdPipeline::writePartClass(
    UsdStageRefPtr prototypesStage,
    const UsdPrim& prototypesPrimOnContainerStage,
    const SdfPath& partPath
) {
    std::optional<SdfReference> defaultParamsRef = StepUsdPipeline::getPrototypesDefaultParams(prototypesPrimOnContainerStage);

    fs::path containerStagePath = fs::canonical(
        prototypesPrimOnContainerStage.GetStage()->GetRootLayer()->GetResolvedPath().GetPathString()
    );
    fs::path prototypesStagePath = fs::canonical(
        prototypesStage->GetRootLayer()->GetResolvedPath().GetPathString()
    );

    fs::path relativePath = fs::relative(containerStagePath, prototypesStagePath.parent_path());

    SdfPath realPartClassPath = this->pathConfig.containerPrimPath.AppendChild(partPath.GetNameToken());
    UsdPrim partPrim = prototypesStage->CreateClassPrim(realPartClassPath);

    prototypesStage->GetPrimAtPath(this->pathConfig.containerPrimPath).SetSpecifier(SdfSpecifierOver);

    UsdGeomImageable(partPrim).CreateVisibilityAttr().Set(UsdGeomTokens->inherited);

    auto makeClassChild = [&](const char* name) {
        SdfPath childPath = realPartClassPath.AppendChild(TfToken(name));
        UsdPrim child = prototypesStage->OverridePrim(childPath);
        UsdGeomImageable(child).CreateVisibilityAttr().Set(UsdGeomTokens->inherited);
    };

    makeClassChild("Mesh");
    makeClassChild("Wireframe");
    makeClassChild("Sketch");
    makeClassChild("SketchPlanes");
    
    if (defaultParamsRef.has_value()) {
        partPrim.GetPrim().GetReferences().AddReference(
            relativePath.string(),
            defaultParamsRef->GetPrimPath(),
            defaultParamsRef->GetLayerOffset()
        );
    }
}

// MARK: - Write Prototype Xforms
void StepUsdPipeline::writePrototypeXformsInPrototypesStage(
    UsdStageRefPtr prototypesStage,
    const std::vector<std::pair<TDF_Label, TopoDS_Shape>>& defs,
    const std::unordered_set<SdfPath, SdfPath::Hash>& selectedPaths,
    const std::string& variantSetName,
    const std::string& variantName,
    const LabelMap<std::string>& definitionNames,
    LabelMap<SdfPath>& prototypePaths,
    bool makeFreshStage
) {
    const int total = (int)defs.size();
    int completed = 0;

    std::string logLabel = "";
    if (!variantSetName.empty()) {
        logLabel = " {" + variantSetName + "=" + variantName + "}";
    }

    std::optional<SdfReference> defaultParamsRef;
    fs::path relativePath;

    UsdGeomXform::Define(prototypesStage, this->pathConfig.containerPrimPath);
    
    SdfPath partPath = this->pathConfig.containerPrimPath.AppendChild(TfToken("Part"));

    for (int defIdx = 0; defIdx < total; defIdx++) {
        const TDF_Label& defLabel = defs[defIdx].first;

        // Guard against already-processed label — use defLabel, not iterator
        if (prototypePaths.count(defLabel)) {
            completed++;
            continue;
        }

        auto it = definitionNames.find(defLabel);
        std::string rawName;
        bool hasRealName = (it != definitionNames.end()
                            && !it->second.empty()
                            && !isAutoGeneratedName(it->second));

        std::string suffix = stableLabelSuffix(defLabel);

        if (hasRealName) {
            rawName = sanitizeUsdName(it->second) + "__" + suffix;
        } else {
            rawName = "__" + suffix;
        }

        SdfPath protoPath = this->pathConfig.prototypesPath.AppendChild(TfToken(rawName));
        prototypePaths[defLabel] = protoPath;

        if (!makeFreshStage && prototypesStage->GetPrimAtPath(protoPath).IsValid()) {
            completed++;
            if (Logger::activeLevel == Logger::DEBUG) {
                //LOG_DEBUG("[" + std::to_string(completed) + "/" + std::to_string(total) + "] Skip existing prototype: " + protoPath.GetString());
            } else {
                LOG_PROGRESS(completed, total, "Writing prototypes " + logLabel);
            }
            continue;
        }

        UsdPrim protoPrim = prototypesStage->DefinePrim(protoPath);

        {
            SdfChangeBlock changeBlock;

            if (!protoPrim.IsValid()) {
                std::cerr << "writePrototypeXform: prim invalid after Define at " << protoPath << "\n";
                continue;
            }

            std::string displayName = hasRealName ? it->second : ("Part_" + suffix);
            protoPrim.SetDisplayName(displayName);
            protoPrim.GetInherits().AddInherit(partPath);

        }

        completed++;
        if (Logger::activeLevel == Logger::DEBUG) {
            LOG_DEBUG("[" + std::to_string(completed) + "/" + std::to_string(total) + "] Writing prototype: " + protoPath.GetString());
        } else {
            LOG_PROGRESS(completed, total, "Writing prototypes " + logLabel);
        }
    }
    LOG_PROGRESS_DONE();
}

void StepUsdPipeline::writePrototypeOverridesInAssemblyStage(
    UsdStageRefPtr assemblyStage,
    LabelMap<SdfPath>& prototypePaths
) {
    LOG_SCOPED_TIMER("writePrototypeOverridesInAssemblyStage");
    const int total = (int)prototypePaths.size();
    int completed = 0;
    
    { // SdfChangeBlock
        SdfChangeBlock changeBlock;

        for (auto protoIter = prototypePaths.begin(); protoIter != prototypePaths.end(); ++protoIter) {
            const SdfPath& protoPath = protoIter->second;
            assemblyStage->OverridePrim(protoPath);

            completed++;
            if (Logger::activeLevel == Logger::DEBUG) {
                LOG_DEBUG("[" + std::to_string(completed) + "/" + std::to_string(total) + "] Writing Assembly Override: " + protoPath.GetString());
            } else {
                LOG_PROGRESS(completed, total, "Writing Prototype Overrides");
            }
        }
        completed = 0;
    }
    { // SdfChangeBlock
        SdfChangeBlock changeBlock;
        for (auto protoIter = prototypePaths.begin(); protoIter != prototypePaths.end(); ++protoIter) {
            const TDF_Label& label = protoIter->first;
            const SdfPath& protoPath = protoIter->second;
            const UsdPrim& protoPrim = assemblyStage->GetPrimAtPath(protoPath);

            TCollection_AsciiString entry;
            TDF_Tool::Entry(label, entry);
            
            AutolibStepAPI api(protoPrim);
            UsdGeomPrimvar labelPrimvar(api.CreateStepLabelAttr());
            labelPrimvar.SetInterpolation(UsdGeomTokens->constant);
            labelPrimvar.Set(TfToken(entry.ToCString()));

            completed++;
            if (Logger::activeLevel == Logger::DEBUG) {
                LOG_DEBUG("[" + std::to_string(completed) + "/" + std::to_string(total) + "] Writing Assembly Override: " + protoPath.GetString());
            } else {
                LOG_PROGRESS(completed, total, "Writing Prototype Overrides");
            }
        }
    } // SdfChangeBlock

    LOG_PROGRESS_DONE();
}

